import assert from 'node:assert/strict';
import {defaults,validateContent,validSlug,publicContent,safeUrl} from '../app/content-model.ts';
import {tax,calculate} from '../app/tax-model.ts';
const page={id:'p1',slug:'pension.html',title:'บำนาญ',description:'',body:'ทดสอบ',kind:'article',published:false,inMenu:true,buttonLabel:'',buttonUrl:''};
assert.equal(validateContent(defaults),true);
assert.equal(validateContent({...defaults,pages:[page]}),true);
assert.equal(validateContent({...defaults,pages:[page,{...page,id:'p2'}]}),false);
for(const slug of ['../admin','api','index.html','ADMIN.html','pension.html/x','//evil.html'])assert.equal(validSlug(slug),false);
assert.equal(validateContent({...defaults,pages:[{...page,buttonUrl:'javascript:alert(1)'}]}),false);
assert.equal(safeUrl('/pension.html'),true);
assert.equal(safeUrl('//evil.example'),false);
assert.deepEqual(publicContent({...defaults,pages:[page]}).pages,[]);
assert.equal(publicContent({...defaults,pages:[{...page,published:true}]}).pages.length,1);
assert.equal(tax(150000),0);assert.equal(tax(300000),7500);assert.equal(tax(500000),27500);assert.equal(tax(1000000),115000);assert.equal(tax(5000000),1265000);assert.equal(tax(6000000),1615000);
let r=calculate({income:1000000,life:0,health:0,pension:300000,retirement:0,other:0});
assert.equal(r.pensionBase,100000);assert.equal(r.pensionExtra,150000);assert.equal(r.net,590000);assert.equal(r.tax,41000);
r=calculate({income:1000000,life:100000,health:25000,pension:300000,retirement:480000,other:0});assert.equal(r.insurance,100000);assert.equal(r.pensionBase,0);assert.equal(r.pensionExtra,20000);
r=calculate({income:0,life:0,health:0,pension:0,retirement:0,other:0});assert.equal(r.tax,0);assert.equal(r.saving,0);
console.log('PASS: legacy content, page validation, draft filtering, unsafe links, tax brackets and shared pension caps');
